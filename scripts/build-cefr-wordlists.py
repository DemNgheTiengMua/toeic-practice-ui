#!/usr/bin/env python3
"""Regenerate gate two's two word resources (#195).

D0.1 defines a band's lexical profile as a share of tokens inside a list: "top 800 families" at
A1, "top 1,800" at A2, "top 3,000" at B1, "top 5,000 + AWL 1-5" at B2, "A1-C1 (AWL 6-10)" at C1.
The repo held no word list at all, so the rule had nothing to divide by. This builds the lists and
writes them once, so the gate reads a fixed artefact rather than whatever a package resolves to.

Outputs
-------
src/BusinessObjects/Authoring/cefr-wordlists.txt
    One headword per line, ordered by CEFR level ascending and then by frequency rank. A band of
    N words is the first N lines, so the nesting the coverage rule relies on (the A1 core is a
    prefix of A1-A2) is structural rather than a property someone has to keep true by hand.
    Columns are tab-separated: headword, level, frequency rank (a low number is a common word).

src/BusinessObjects/Authoring/awl-sublists.txt
    One line per AWL headword: headword, sublist 1-10. Only single words; the AWL's multi-word
    headwords are dropped because a token counter cannot see them anyway.

Provenance and terms
--------------------
* CEFR level: CEFR-J Vocabulary Profile 1.5 (A1-B2) and the Octanove Vocabulary Profile C1/C2 1.0,
  both published by Open Language Profiles, https://github.com/openlanguageprofiles/olp-en-cefrj
  CEFR-J: free for research and commercial use with citation; copyright Tono Laboratory, TUFS.
  Citation: Tono, Y. (ed.) The CEFR-J Wordlist Version 1.5. Tokyo University of Foreign Studies.
  Octanove C1/C2: CC BY-SA 4.0.
* Order inside a level: hermitdave FrequencyWords `en_50k` (OpenSubtitles 2018), which is a spoken
  corpus, so the A1 core leads with words a learner actually hears.
* AWL: Averil Coxhead's Academic Word List, sublists 1-10, from
  https://github.com/TheoSeo93/Academic_Words_list (Open Software License 1.1).

Known limits, stated rather than hidden:
* 873 of the CEFR-J/Octanove headwords never appear in `en_50k`; they sort to the end of their
  level rather than being dropped, so the 5,000-word boundary is a frequency claim about the
  sources, not a claim about a corpus this repo holds.
* A CEFR-J level is a *learning* judgement, not a frequency count. The two disagree at the
  margins, and the lower (easier) of two disagreeing levels wins: a word a learner meets early
  must not be refused as late.
* Inflections are folded to their headword only by the simple suffix rule in GateTwo, so
  irregular forms ("bought" for "buy") fall outside the list and count as off-list.

Usage:  python scripts/build-cefr-wordlists.py
"""

import re
import urllib.request

CEFRJ = "https://raw.githubusercontent.com/openlanguageprofiles/olp-en-cefrj/master/cefrj-vocabulary-profile-1.5.csv"
OCTANOVE = "https://raw.githubusercontent.com/openlanguageprofiles/olp-en-cefrj/master/octanove-vocabulary-profile-c1c2-1.0.csv"
FREQ = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/en/en_50k.txt"
AWL = "https://raw.githubusercontent.com/TheoSeo93/Academic_Words_list/HEAD/data/AWL.txt"
OUT_WORDS = "src/BusinessObjects/Authoring/cefr-wordlists.txt"
OUT_AWL = "src/BusinessObjects/Authoring/awl-sublists.txt"

ORDER = ["A1", "A2", "B1", "B2", "C1", "C2"]
WORD = re.compile(r"^[a-z][a-z'-]*$")


def fetch(url):
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def headword(raw):
    """'a.m./A.M./am/AM' -> 'am'; 'analyze/analyse' -> 'analyze'. Single words only."""
    first = raw.split("/")[0].strip().lower()
    first = re.sub(r"[^a-z'-]", "", first)
    return first if WORD.match(first) else None


def word_lists():
    frequency = {}
    for rank, line in enumerate(fetch(FREQ).splitlines()):
        word = line.split(" ")[0]
        if word not in frequency:
            frequency[word] = rank

    levels = {}
    for url in (CEFRJ, OCTANOVE):
        for line in fetch(url).splitlines()[1:]:
            parts = line.split(",")
            if len(parts) < 3:
                continue
            word, level = headword(parts[0]), parts[2].strip()
            if word is None or level not in ORDER:
                continue
            current = levels.get(word)
            if current is None or ORDER.index(level) < ORDER.index(current):
                levels[word] = level

    ordered = sorted(
        levels.items(),
        key=lambda item: (ORDER.index(item[1]), frequency.get(item[0], 10 ** 9), item[0]),
    )

    header = [
        "# CEFR word list for gate two (#195). Generated by scripts/build-cefr-wordlists.py.",
        "# Columns: headword <tab> CEFR level <tab> frequency rank (lower is more common).",
        "# Ordered by level ascending, then frequency: a band of N words is the first N lines.",
        "# Level: CEFR-J Vocabulary Profile 1.5 (A1-B2) + Octanove C1/C2 1.0, from",
        "# https://github.com/openlanguageprofiles/olp-en-cefrj. CEFR-J (c) Tono Laboratory, TUFS;",
        "# free for research and commercial use with citation. Octanove C1/C2: CC BY-SA 4.0.",
        "# Order within a level: hermitdave FrequencyWords en_50k (OpenSubtitles 2018).",
    ]
    with open(OUT_WORDS, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(header) + "\n")
        for word, level in ordered:
            handle.write(f"{word}\t{level}\t{frequency.get(word, 999999)}\n")

    print(f"{len(ordered)} headwords -> {OUT_WORDS}")
    counts = {level: sum(1 for _, l in ordered if l == level) for level in ORDER}
    cumulative = 0
    for level in ORDER:
        cumulative += counts[level]
        print(f"  {level}: {counts[level]:5d}  cumulative {cumulative:5d}")
    for size in (800, 1800, 3000, 5000):
        print(f"  first {size}: {ordered[size - 1][0]}")


def awl_sublists():
    """AWL headwords are the unindented lines; the indented ones are their family members."""
    rows, sublist = [], 0
    for line in fetch(AWL).splitlines():
        match = re.search(r"Sublist\s+(\d+)", line)
        if match:
            sublist = int(match.group(1))
            continue
        if not sublist or line.startswith("\t"):
            continue
        word = headword(line.strip())
        if word:
            rows.append((word, sublist))

    header = [
        "# Academic Word List headwords by sublist, for gate two's B2 and C1 coverage (#195).",
        "# Generated by scripts/build-cefr-wordlists.py. Columns: headword <tab> sublist.",
        "# Source: Averil Coxhead's Academic Word List, via",
        "# https://github.com/TheoSeo93/Academic_Words_list (Open Software License 1.1).",
        "# Family members are folded to their headword only if the sublist file lists them as heads;",
        "# inflected forms are matched by GateTwo's suffix rule.",
    ]
    with open(OUT_AWL, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(header) + "\n")
        for word, sublist in rows:
            handle.write(f"{word}\t{sublist}\n")

    print(f"{len(rows)} AWL headwords -> {OUT_AWL}")
    for sublist in range(1, 11):
        print(f"  sublist {sublist}: {sum(1 for _, s in rows if s == sublist)}")


if __name__ == "__main__":
    word_lists()
    awl_sublists()
